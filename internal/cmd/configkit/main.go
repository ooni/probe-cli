package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
)

var (
	// helpFlag is the -help flag
	helpFlag = flag.Bool("help", false, "Show the help message")

	// outputFlag is the -output flag
	outputFlag = flag.String("output", "", "path of the generated Go file to write")

	// packageFlag is the -package flag
	packageFlag = flag.String("package", "", "Go package name for the generated file")

	// schemaFlag is the -schema flag
	schemaFlag = flag.String("schema", "", "JSON Schema file to generate from")

	// osExitFn allows overwriting os.Exit in tests
	osExitFn = os.Exit
)

// topLevel is the subset of a schema file we need at the top level.
type topLevel struct {
	Description string `json:"description"`
	XOONI       struct {
		GoType string `json:"goType"`
	} `json:"x-ooni"`
	Properties json.RawMessage `json:"properties"`
}

// propSpec is the subset of a single JSON Schema property we care about.
type propSpec struct {
	Type        string `json:"type"`
	Description string `json:"description"`
	XOONI       struct {
		Name string `json:"name"`
	} `json:"x-ooni"`
}

// orderedProp is a property together with its JSON/wire key.
type orderedProp struct {
	key  string
	spec propSpec
}

// moduleRoot walks up from the current directory until it finds the dir
// containing go.mod.
func moduleRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		log.Fatal(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			log.Fatal("configkit: cannot find go.mod walking up from cwd")
		}
		dir = parent
	}
}

// goTypeForJSON maps a JSON Schema scalar type to the Go type we emit. We only
// support the scalar kinds handled by the registry reflection path.
func goTypeForJSON(jsonType string) string {
	switch jsonType {
	case "boolean":
		return "bool"
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "string":
		return "string"
	default:
		log.Fatalf("configkit: unsupported JSON Schema type %q", jsonType)
		return "" // not reached
	}
}

// parseOrderedProperties decodes the spec properties preserving the order.
func parseOrderedProperties(raw json.RawMessage) []orderedProp {
	dec := json.NewDecoder(bytes.NewReader(raw))
	if _, err := dec.Token(); err != nil {
		log.Fatalf("configkit: cannot read properties object: %s", err)
	}

	var out []orderedProp
	for dec.More() {
		keyTok, err := dec.Token()
		if err != nil {
			log.Fatalf("configkit: cannot read property key: %s", err)
		}
		key, ok := keyTok.(string)
		if !ok {
			log.Fatalf("configkit: unexpected property key token %v", keyTok)
		}

		var spec propSpec
		if err := dec.Decode(&spec); err != nil {
			log.Fatalf("configkit: cannot decode property %q: %s", key, err)
		}
		if spec.XOONI.Name == "" {
			log.Fatalf("configkit: property %q is missing x-ooni.name", key)
		}
		out = append(out, orderedProp{key: key, spec: spec})
	}
	return out
}

// generate reads the schema at schemaPath and writes the corresponding Config
// struct to outPath as part of the given Go package. The root is the module
// root, used to render a stable, machine-independent path in the file header.
func generate(root, schemaPath, outPath, pkg string) {
	data, err := os.ReadFile(schemaPath)
	if err != nil {
		log.Fatal(err)
	}
	var top topLevel
	if err := json.Unmarshal(data, &top); err != nil {
		log.Fatalf("configkit: cannot parse %s: %s", schemaPath, err)
	}
	if top.XOONI.GoType == "" {
		log.Fatalf("configkit: %s is missing x-ooni.goType", schemaPath)
	}
	props := parseOrderedProperties(top.Properties)

	// Render the schema path relative to the module root so the generated
	// header is identical regardless of where the module lives on disk.
	schemaDisplay, err := filepath.Rel(root, schemaPath)
	if err != nil {
		schemaDisplay = filepath.Base(schemaPath)
	}
	schemaDisplay = filepath.ToSlash(schemaDisplay)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by configkit from %s; DO NOT EDIT.\n\n",
		schemaDisplay)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	if top.Description != "" {
		fmt.Fprintf(&b, "// %s\n", top.Description)
	}
	fmt.Fprintf(&b, "type %s struct {\n", top.XOONI.GoType)
	for _, p := range props {
		tag := fmt.Sprintf("`json:%q ooni:%q`", p.key, p.spec.Description)
		fmt.Fprintf(&b, "\t%s %s %s\n", p.spec.XOONI.Name, goTypeForJSON(p.spec.Type), tag)
	}
	fmt.Fprintf(&b, "}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("configkit: cannot gofmt generated code for %s: %s", schemaPath, err)
	}

	if err := os.WriteFile(outPath, formatted, 0644); err != nil {
		log.Fatal(err)
	}
	log.Printf("configkit: wrote %s", outPath)
}

// resolvePath makes a relative flag path absolute against the module root.
func resolvePath(root, path string) string {
	if filepath.IsAbs(path) {
		return path
	}
	return filepath.Join(root, path)
}

func main() {
	log.SetFlags(0)
	flag.Parse()
	if *helpFlag || *schemaFlag == "" || *outputFlag == "" || *packageFlag == "" {
		fmt.Fprintf(os.Stderr, "\n")
		fmt.Fprintf(os.Stderr, "usage: %s -schema <file> -output <file> -package <name>\n", filepath.Base(os.Args[0]))
		fmt.Fprintf(os.Stderr, "\n")
		fmt.Fprintf(os.Stderr, "Generates a richer-input experiment Config struct from a JSON Schema.\n")
		fmt.Fprintf(os.Stderr, "\n")
		fmt.Fprintf(os.Stderr, "Reads the JSON Schema at -schema <file> and writes the generated Go file\n")
		fmt.Fprintf(os.Stderr, "to -output <file> as part of the -package <name> Go package. The -schema\n")
		fmt.Fprintf(os.Stderr, "and -output paths are resolved against the module root when relative.\n")
		fmt.Fprintf(os.Stderr, "\n")
		osExitFn(1)
		return
	}

	root := moduleRoot()
	generate(root, resolvePath(root, *schemaFlag), resolvePath(root, *outputFlag), *packageFlag)
}
