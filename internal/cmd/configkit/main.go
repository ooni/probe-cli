package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"github.com/ooni/probe-cli/v3/internal/experimentname"
	"github.com/ooni/probe-cli/v3/internal/registry"
	"github.com/ooni/probe-cli/v3/internal/version"
)

var (
	// helpFlag is the -help flag.
	helpFlag = flag.Bool("help", false, "Show the help message")

	// outputDirFlag is the -output-dir flag.
	outputDirFlag = flag.String("output-dir", "schemas", "directory to write the generated schemas into")

	// checkFlag is the -check flag.
	checkFlag = flag.Bool("check", false, "verify the committed schemas are up to date instead of writing them")

	// osExitFn allows overwriting os.Exit in tests
	osExitFn = os.Exit
)

// moduleRoot walks up from the current directory until it finds the dir
// containing go.mod.
func moduleRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		log.Fatal(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			log.Fatal("configkit: cannot find go.mod walking up from cwd")
		}
		dir = parent
	}
}

// mapKind maps a Go field kind to the JSON Schema type we emit.
func mapKind(k reflect.Kind) (string, error) {
	switch k {
	case reflect.String:
		return "string", nil
	case reflect.Int64, reflect.Int, reflect.Int32:
		return "integer", nil
	case reflect.Bool:
		return "boolean", nil
	default:
		return "", fmt.Errorf("unsupported field kind %q", k)
	}
}

// jsonKey returns the property key for a struct field.
func jsonKey(f reflect.StructField) string {
	tag := f.Tag.Get("json")
	if tag == "" {
		return f.Name
	}

	name, _, _ := strings.Cut(tag, ",")
	if name == "" {
		return f.Name
	}
	return name
}

// property is one schema property in declaration order.
type property struct {
	key  string
	typ  string
	desc string
}

// schemaProperties reflects over a Config struct type and returns its settable
// properties in declaration order.
func schemaProperties(t reflect.Type) ([]property, error) {
	var out []property
	for f := range t.Fields() {
		if !f.IsExported() {
			continue
		}
		doc := f.Tag.Get("ooni")
		if doc == "" {
			continue
		}
		typ, err := mapKind(f.Type.Kind())
		if err != nil {
			return nil, fmt.Errorf("%s.%s: %w", t.Name(), f.Name, err)
		}
		out = append(out, property{key: jsonKey(f), typ: typ, desc: doc})
	}
	return out, nil
}

// orderedObject is a JSON object that marshals its members in insertion order
type orderedObject []member

// member is one key/value pair of an [orderedObject].
type member struct {
	key string
	val any
}

// MarshalJSON implements [json.Marshaler].
func (o orderedObject) MarshalJSON() ([]byte, error) {
	var b bytes.Buffer
	b.WriteByte('{')
	for i, m := range o {
		if i > 0 {
			b.WriteByte(',')
		}
		k, err := json.Marshal(m.key)
		if err != nil {
			return nil, err
		}
		b.Write(k)
		b.WriteByte(':')
		v, err := json.Marshal(m.val)
		if err != nil {
			return nil, err
		}
		b.Write(v)
	}
	b.WriteByte('}')
	return b.Bytes(), nil
}

// renderSchema builds the indented JSON Schema document for an experiment.
func renderSchema(name, experimentVersion string, props []property) ([]byte, error) {
	properties := orderedObject{}
	for _, p := range props {
		properties = append(properties, member{key: p.key, val: orderedObject{
			{key: "type", val: p.typ},
			{key: "description", val: p.desc},
		}})
	}
	doc := orderedObject{
		{key: "$schema", val: "https://json-schema.org/draft/2020-12/schema"},
		{key: "$comment", val: "generated by `go run ./internal/cmd/configkit`; DO NOT EDIT."},
		{key: "experiment_name", val: name},
		{key: "title", val: fmt.Sprintf("%s experiment config", name)},
		{key: "version", val: version.Version},
		{key: "experiment_version", val: experimentVersion},
		{key: "type", val: "object"},
		{key: "properties", val: properties},
	}
	out, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}

// schemaForExperiment produces the schema bytes for a single experiment.
func schemaForExperiment(name string, factory *registry.Factory) ([]byte, error) {
	t, err := factory.ConfigType()
	if err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	props, err := schemaProperties(t)
	if err != nil {
		return nil, err
	}
	experimentVersion := factory.NewExperimentMeasurer().ExperimentVersion()
	return renderSchema(name, experimentVersion, props)
}

// schemaPath returns the on-disk path of an experiment's schema.
func schemaPath(outputDir, name string) string {
	n := experimentname.Parse(name)
	if n.Version == "" {
		return filepath.Join(outputDir, n.Base, "config.json")
	}
	return filepath.Join(outputDir, n.Base, n.Version, "config.json")
}

// run generates and verifies all schemas.
func run(outputDir string, check bool) (drift int, err error) {
	factories := registry.RegisteredFactories()
	names := make([]string, 0, len(factories))
	for name := range factories {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		want, err := schemaForExperiment(name, factories[name]())
		if err != nil {
			return drift, err
		}
		path := schemaPath(outputDir, name)

		if check {
			got, rerr := os.ReadFile(path)
			if rerr != nil || !bytes.Equal(got, want) {
				log.Printf("configkit: out of date: %s", path)
				drift++
			}
			continue
		}

		if mkerr := os.MkdirAll(filepath.Dir(path), 0755); mkerr != nil {
			return drift, mkerr
		}
		if werr := os.WriteFile(path, want, 0644); werr != nil {
			return drift, werr
		}
		log.Printf("configkit: wrote %s", path)
	}
	return drift, nil
}

func main() {
	log.SetFlags(0)
	flag.Parse()
	if *helpFlag {
		fmt.Fprintf(os.Stderr, "\n")
		fmt.Fprintf(os.Stderr, "usage: %s [-output-dir <dir>] [-check]\n", filepath.Base(os.Args[0]))
		fmt.Fprintf(os.Stderr, "\n")
		fmt.Fprintf(os.Stderr, "Generates a JSON Schema describing each experiment's settable Config\n")
		fmt.Fprintf(os.Stderr, "Writes one <output-dir>/<experiment>/config.json per experiment\n")
		fmt.Fprintf(os.Stderr, "\n")
		osExitFn(1)
	}

	outputDir := *outputDirFlag
	if !filepath.IsAbs(outputDir) {
		outputDir = filepath.Join(moduleRoot(), outputDir)
	}

	drift, err := run(outputDir, *checkFlag)
	if err != nil {
		log.Fatalf("configkit: %s", err)
	}
	if *checkFlag && drift > 0 {
		log.Fatalf("configkit: %d schema(s) out of date; run `go run ./internal/cmd/configkit`", drift)
	}
}
