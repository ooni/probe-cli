func TestGoTypeForJSON(t *testing.T) {
	tests := map[string]string{
		"boolean": "bool",
		"integer": "int64",
		"number":  "float64",
		"string":  "string",
	}
	for in, want := range tests {
		if got := goTypeForJSON(in); got != want {
			t.Errorf("goTypeForJSON(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestParseOrderedPropertiesPreservesOrder(t *testing.T) {
	raw := json.RawMessage(`{
		"zebra": {"type": "string", "description": "z", "x-ooni": {"name": "Zebra"}},
		"alpha": {"type": "boolean", "description": "a", "x-ooni": {"name": "Alpha"}},
		"mike":  {"type": "integer", "description": "m", "x-ooni": {"name": "Mike"}}
	}`)

	got := parseOrderedProperties(raw)

	wantKeys := []string{"zebra", "alpha", "mike"}
	wantNames := []string{"Zebra", "Alpha", "Mike"}
	if len(got) != len(wantKeys) {
		t.Fatalf("got %d props, want %d", len(got), len(wantKeys))
	}
	for i := range got {
		if got[i].key != wantKeys[i] {
			t.Errorf("prop %d: key = %q, want %q", i, got[i].key, wantKeys[i])
		}
		if got[i].spec.XOONI.Name != wantNames[i] {
			t.Errorf("prop %d: name = %q, want %q", i, got[i].spec.XOONI.Name, wantNames[i])
		}
	}
}

func TestGenerate(t *testing.T) {
	schemaPath := filepath.Join("testdata", "example.json")
	outPath := filepath.Join(t.TempDir(), "out.go")
	generate(".", schemaPath, outPath, "exampleexp")

	data, err := os.ReadFile(outPath)
	if err != nil {
		t.Fatal(err)
	}
	out := string(data)

	wantHeader := "// Code generated by configkit from testdata/example.json; DO NOT EDIT."
	if !strings.Contains(out, wantHeader) {
		t.Errorf("missing header %q in:\n%s", wantHeader, out)
	}
	if !strings.Contains(out, "package exampleexp") {
		t.Errorf("missing package clause in:\n%s", out)
	}
	if !strings.Contains(out, "// Config contains the experiment's configuration.") {
		t.Errorf("missing doc comment in:\n%s", out)
	}
	if !strings.Contains(out, "type Config struct {") {
		t.Errorf("missing struct declaration in:\n%s", out)
	}

	// Tags carry the wire key and the ooni description
	for _, tag := range []string{
		`json:"domain" ooni:"the domain"`,
		`json:"enabled" ooni:"whether enabled"`,
	} {
		if !strings.Contains(out, tag) {
			t.Errorf("missing tag %q in:\n%s", tag, out)
		}
	}

	// Field order must match schema order: domain before enabled.
	if i, j := strings.Index(out, `json:"domain"`), strings.Index(out, `json:"enabled"`); i < 0 || j < 0 || i > j {
		t.Errorf("fields missing or out of order (domain@%d, enabled@%d):\n%s", i, j, out)
	}

	// Each field must carry the Go type its JSON type maps to.
	for line := range strings.SplitSeq(out, "\n") {
		if strings.Contains(line, "Domain") && !strings.Contains(line, "string") {
			t.Errorf("Domain field not typed string: %q", line)
		}
		if strings.Contains(line, "Enabled") && !strings.Contains(line, "bool") {
			t.Errorf("Enabled field not typed bool: %q", line)
		}
	}
}
